"""Build the web brand assets in app/static/brand/ from mediaassets/Taskbrigade_logo.png.

Run from the repository root:  uv run --no-project --with pillow --with resvg-py python mediaassets/build_brand.py

- The mark (dots, fork paths, arrow) is redrawn as SVG with the brand colours (coordinates of the source PNG).
- The header/README logo is the source PNG, freed from its white background and recoloured to the exact brand
  colours: "Task", the flame on the i and the middle path in steel blue, "Brigade" and the outer paths in orange.
"""

import io
from pathlib import Path

import resvg_py
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "mediaassets" / "Taskbrigade_logo.png"
OUT = ROOT / "app" / "static" / "brand"

BLUE = (0x28, 0x5F, 0x87)    # steel blue
ORANGE = (0xD9, 0x5D, 0x39)  # fire orange
FLAME = (1255, 255, 1345, 345)  # flame above the i of "Brigade" (source pixels)
CROP = (140, 244, 1856, 542)    # logo bounding box plus a small margin

SHAPES = f"""<g fill="#{bytes(ORANGE).hex().upper()}">
<circle cx="185" cy="290" r="37"/><circle cx="185" cy="482" r="37"/>
<path id="f" d="M232 271H280C305 271 318 285 340 307C362 330 380 345 440 357V369C385 369 357 361 336 343C314 323 304 311 280 311H232A51 51 0 0 1 232 271Z"/>
<use href="#f" transform="matrix(1 0 0 -1 0 772)"/>
</g>
<g fill="#{bytes(BLUE).hex().upper()}">
<circle cx="185" cy="386" r="37"/>
<path d="M230 371H344C362 371 364 381 384 381H452V391H384C364 391 362 401 344 401H230A47 47 0 0 1 230 371Z"/>
<path d="M452 323L545 386L452 449Z"/>
</g>"""


# Below ~48 px the fine tapers of the mark disappear: the favicon is a simplified mark with bold strokes.
FAVICON = f"""<g fill="#{bytes(ORANGE).hex().upper()}"><circle cx="5" cy="6" r="4"/><circle cx="5" cy="26" r="4"/></g>
<g fill="none" stroke="#{bytes(ORANGE).hex().upper()}" stroke-width="3.2">
<path d="M10 6H12.5C16.5 6 16.5 12 21.5 12"/><path d="M10 26H12.5C16.5 26 16.5 20 21.5 20"/></g>
<g fill="#{bytes(BLUE).hex().upper()}"><circle cx="5" cy="16" r="4"/><path d="M10 14.6H22V17.4H10Z"/>
<path d="M21 8.5L31.5 16L21 23.5Z"/></g>"""


def svg(view_box: str, body: str, comment: str) -> str:
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view_box}"><!-- TaskBrigade {comment}, '
            f"generated by mediaassets/build_brand.py -->\n{body}\n</svg>\n")


def render(svg_text: str, size: int) -> Image.Image:
    png = bytes(resvg_py.svg_to_bytes(svg_string=svg_text, width=size, height=size))
    return Image.open(io.BytesIO(png)).convert("RGBA")


def save_png(img: Image.Image, name: str) -> None:
    # A 64-colour palette keeps the anti-aliased edges and makes the files several times smaller.
    img.quantize(64, method=Image.Quantize.FASTOCTREE).save(OUT / name, optimize=True)


def freed_logo() -> Image.Image:
    """Source logo as RGBA: exact brand colour per pixel, alpha from its distance to the white background."""
    src = Image.open(SOURCE).convert("RGB").crop(CROP)
    out = Image.new("RGBA", src.size)
    sp, op = src.load(), out.load()
    fx0, fy0, fx1, fy1 = (FLAME[0] - CROP[0], FLAME[1] - CROP[1], FLAME[2] - CROP[0], FLAME[3] - CROP[1])
    for y in range(src.height):
        for x in range(src.width):
            r, g, b = sp[x, y]
            colour = BLUE if b > r or (fx0 <= x < fx1 and fy0 <= y < fy1) else ORANGE
            ref = BLUE if b > r else ORANGE  # alpha is measured against the colour the pixel really has
            d = (255 - r, 255 - g, 255 - b)
            dc = tuple(255 - c for c in ref)
            a = sum(i * j for i, j in zip(d, dc)) / sum(j * j for j in dc)
            a = 0.0 if a < 0.06 else min(1.0, a)  # drop the faint noise of the white background
            op[x, y] = (*colour, round(a * 255))
    return out


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "mark.svg").write_text(svg("140 244 416 284", SHAPES, "mark"))
    favicon = svg("0 0 32 32", FAVICON, "favicon")
    (OUT / "favicon.svg").write_text(favicon)
    app_icon = svg("58 96 580 580", '<rect x="58" y="96" width="580" height="580" rx="128" fill="#FFFFFF"/>\n'
                   + SHAPES, "app icon")
    (OUT / "app-icon.svg").write_text(app_icon)
    save_png(render(favicon, 32), "favicon-32.png")
    # iOS rounds the corners itself and shows transparency as black: square, opaque white tile.
    touch = svg("58 96 580 580", '<rect x="58" y="96" width="580" height="580" fill="#FFFFFF"/>\n' + SHAPES,
                "touch icon")
    save_png(render(touch, 180), "apple-touch-icon.png")
    save_png(render(app_icon, 512), "app-icon-512.png")

    logo = freed_logo()
    for height, name in ((36, "logo.png"), (72, "logo@2x.png"), (120, "logo-readme.png")):
        width = round(logo.width * height / logo.height)
        save_png(logo.resize((width, height), Image.Resampling.LANCZOS), name)


if __name__ == "__main__":
    main()
